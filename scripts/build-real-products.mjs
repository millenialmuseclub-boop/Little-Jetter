// Converts scripts/_ltk-import.csv (pasted LTK affiliate list export) plus
// the existing hand-picked catalog entries (kept for their real product
// photos) into src/data/realProducts.ts — a single typed catalog consumed
// by both the Shop tab's category drawers and the "Parent product matches"
// panels. Run with: npx tsx scripts/build-real-products.mjs
import fs from 'node:fs';
import path from 'node:path';
import { realProductCatalog as legacyCatalog } from './build-real-products-legacy-source.ts';

const CSV_PATH = path.resolve('scripts/ltk-import.csv');
const OUT_PATH = path.resolve('src/data/realProducts.ts');
const OVERRIDES_PATH = path.resolve('scripts/product-image-overrides.json');
const imageOverrides = fs.existsSync(OVERRIDES_PATH)
  ? JSON.parse(fs.readFileSync(OVERRIDES_PATH, 'utf8'))
  : {};

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else { inQuotes = false; }
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); field = ''; rows.push(row); row = []; }
    else if (c === '\r') { /* skip */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows.filter((r) => r.length === header.length && r[0]).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
}

const CATEGORY_MAP = {
  shoe: 'shoe', luggage: 'luggage', toy: 'toy', top: 'top', bottom: 'bottom',
  dress: 'dress', outerwear: 'outerwear', accessory: 'accessory', book: 'book', swim: 'swim',
};

const csvText = fs.readFileSync(CSV_PATH, 'utf8');
const rows = parseCsv(csvText);
const seenIds = new Set(legacyCatalog.map((p) => p.id));
const newEntries = rows.map((r) => {
  let id = slugify(r.item_name);
  let n = 2;
  while (seenIds.has(id)) { id = `${slugify(r.item_name)}-${n}`; n++; }
  seenIds.add(id);
  const category = CATEGORY_MAP[r.category.trim()] ?? 'accessory';
  return {
    id, playItemId: '__general__', category,
    brand: r.brand.trim(), name: r.item_name.trim(),
    price: Number(r.price_usd), imageUrl: imageOverrides[id] ?? '', sourceUrl: r.url.trim(),
    provider: 'ltk', verifiedAt: imageOverrides[id] ? '2026-09-04' : '2026-09-03', childMode: 'view-only',
    listId: r.list_id.trim(), listName: r.list_name.trim(),
  };
});

// Legacy hand-picked items keep their real product photos and playItemId
// matches (used by the doll's "Parent product matches" auto-suggestions).
// Old category values ('clothing'/'shoes') remapped onto the same
// top/bottom/dress/outerwear/shoe/accessory/luggage/toy/book/swim taxonomy
// as the CSV import, by id since a handful of "clothing" entries are
// actually outerwear/bottoms, not tops.
const LEGACY_CATEGORY = {
  hoodie: 'outerwear', sweatpants: 'bottom',
};

const legacyEntries = legacyCatalog.map((p) => ({
  id: p.id, playItemId: p.playItemId,
  category: LEGACY_CATEGORY[p.id] ?? (p.category === 'shoes' ? 'shoe' : p.category === 'clothing' ? 'top' : p.category),
  brand: p.brand, name: p.name, imageUrl: p.imageUrl, sourceUrl: p.sourceUrl || '',
  provider: 'ltk', verifiedAt: p.verifiedAt, childMode: 'view-only',
}));

const allEntries = [...legacyEntries, ...newEntries];

const ts = `// Auto-generated by scripts/build-real-products.mjs — do not hand-edit the
// entry list, re-run the script instead (it reads scripts/_ltk-import.csv
// for new items and src/catalog.ts's legacy savedLTKPicks for the
// hand-picked ones with real product photos).
export type ProductCategory = 'top' | 'bottom' | 'dress' | 'outerwear' | 'shoe' | 'accessory' | 'luggage' | 'toy' | 'book' | 'swim';

export type RealProductReference = {
  id: string;
  playItemId: string;
  category: ProductCategory;
  brand: string;
  name: string;
  price?: number;
  imageUrl: string;
  sourceUrl: string;
  provider: 'ltk';
  verifiedAt: string;
  childMode: 'view-only';
  listId?: string;
  listName?: string;
};

export const realProductCatalog: RealProductReference[] = ${JSON.stringify(allEntries, null, 2)};
`;

fs.writeFileSync(OUT_PATH, ts, 'utf8');
console.log(`Wrote ${allEntries.length} products (${legacyEntries.length} legacy + ${newEntries.length} from CSV) to ${OUT_PATH}`);
